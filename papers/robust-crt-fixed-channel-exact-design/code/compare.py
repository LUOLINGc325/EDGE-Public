#!/usr/bin/env python3
"""Compare author CRT solver to independently precomputed global references.

The reference file was generated by enumerating every tuple from [2,M_max]
before this script imported the author solver. No localized reference search
or author-generated expected values are used.
"""

from __future__ import annotations

from datetime import datetime, timezone
from fractions import Fraction
from hashlib import sha256
import importlib.util
from itertools import combinations
import json
from math import gcd, prod
from pathlib import Path
import platform
from time import perf_counter


ROOT = Path(__file__).resolve().parent.parent
REFERENCE = ROOT / "results/independent_reference.json"
SOLVER = ROOT / "code/solve.py"
PAPER = ROOT / "paper.en.md"
OUTPUT = ROOT / "results/independent_comparison.json"


def digest(path: Path) -> str:
    return sha256(path.read_bytes()).hexdigest()


def feasible(bases: list[int], L: int) -> bool:
    return (
        len(bases) == L and bases == sorted(set(bases)) and bases[0] >= 2
        and all(gcd(a, b) == 1 for a, b in combinations(bases, 2))
    )


def main() -> None:
    start = perf_counter()
    reference = json.loads(REFERENCE.read_text(encoding="utf-8"))
    spec = importlib.util.spec_from_file_location("author_crt_solver", SOLVER)
    assert spec is not None and spec.loader is not None
    solver = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(solver)
    comparisons = []
    for dataset in reference["exhaustive_capacity"]:
        L = dataset["L"]
        table = {row["M"]: row for row in dataset["capacity_table"]}
        capacity_count = 0
        for M in range(dataset["M_max"] + 1):
            actual = solver.capacity_local(L, M, anchored=False)
            expected = table[M]["capacity"] if M >= 2 else 0
            assert actual["capacity"] == expected, (L, M, actual, expected)
            if expected:
                assert feasible(actual["witness"], L), (L, M, actual)
                assert actual["witness"][-1] <= M
                assert prod(actual["witness"][:-1]) == expected
            else:
                assert actual["witness"] is None
            capacity_count += 1

        inverse_count = 0
        rational_count = 0
        for query in dataset["inverse_threshold_queries"]:
            R = query["R"]
            answer = solver.optimize(L, R)
            assert answer["largest_base"] == query["optimal_maximum"], (L, R, answer, query)
            assert feasible(answer["bases"], L)
            assert prod(answer["bases"][:-1]) == answer["product_smallest"] >= R
            assert answer["bases"][-1] == answer["largest_base"]
            inverse_count += 1
            # Every tested fractional threshold is strictly positive and has
            # ceiling R. This checks exact rational normalization independently.
            half_below = Fraction(2 * R - 1, 2)
            rational_answer = solver.optimize(L, str(half_below))
            assert rational_answer["integer_threshold"] == R
            assert rational_answer["largest_base"] == query["optimal_maximum"]
            assert feasible(rational_answer["bases"], L)
            rational_count += 1

        comparisons.append({
            "channels": L,
            "budget_range": [0, dataset["M_max"]],
            "global_capacity_comparisons": capacity_count,
            "integer_threshold_queries": inverse_count,
            "rational_ceiling_queries": rational_count,
            "all_passed": True,
            "reference_all_tuples": dataset["all_tuples_tested"],
            "reference_scope": "Full interval enumeration, including every maximizer in the finite range.",
        })

    large = []
    for L in (5, 6):
        for exponent in (4, 8, 20, 100, 500):
            case_start = perf_counter()
            answer = solver.optimize(L, 10 ** exponent)
            elapsed = perf_counter() - case_start
            assert feasible(answer["bases"], L)
            assert prod(answer["bases"][:-1]) == answer["product_smallest"] >= 10 ** exponent
            assert answer["bases"][-1] == answer["largest_base"]
            # No independent global optimum oracle is claimed at these sizes.
            large.append({
                "channels": L,
                "threshold_description": f"10^{exponent}",
                "threshold_bits": (10 ** exponent).bit_length(),
                "largest_base": answer["largest_base"],
                "bases": answer["bases"],
                "elapsed_seconds": elapsed,
                "search_counts": answer["counts"],
                "finite_feasibility_passed": True,
                "independent_global_optimality_check": False,
            })

    report = {
        "schema": "robust-crt-independent-author-comparison/v1",
        "python": platform.python_version(),
        "comparison_script_sha256": digest(Path(__file__)),
        "reference_report_sha256": digest(REFERENCE),
        "reference_generator_sha256": reference["script_sha256"],
        "author_solver_sha256": digest(SOLVER),
        "manuscript_sha256_at_run": digest(PAPER),
        "comparisons": comparisons,
        "large_input_runs": large,
        "total_elapsed_seconds": perf_counter() - start,
        "method_separation": "The full-interval reference predates inspection of the author solver; it uses no window, templates, graph search, pruning, root estimate, or author code. Author results are compared by capacities and minima, not by deterministic witness equality.",
        "scope_limit": "Finite implementation comparison and large-input feasibility/timing observations only. All-input correctness and practical worst-case bounds depend on the written proofs. Timing observations are specific to this runtime and are not hardware-independent performance guarantees.",
        "formalization": {"lean_written": False, "lean_run": False},
        "status": "PASS_ALL_STATED_FINITE_CHECKS",
    }
    OUTPUT.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "report": str(OUTPUT),
        "status": report["status"],
        "capacities": sum(x["global_capacity_comparisons"] for x in comparisons),
        "integer_inverse_queries": sum(x["integer_threshold_queries"] for x in comparisons),
        "rational_inverse_queries": sum(x["rational_ceiling_queries"] for x in comparisons),
        "large_feasibility_runs": len(large),
        "largest_case_seconds": max(x["elapsed_seconds"] for x in large),
        "total_seconds": report["total_elapsed_seconds"],
        "solver_sha256": report["author_solver_sha256"],
        "paper_sha256": report["manuscript_sha256_at_run"],
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
